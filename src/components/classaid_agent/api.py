bp = Blueprint('classaid_agent', __name__, url_prefix='/classaid', template_folder='templates')

MAX_QUESTION_CHARS = 4000
RATING_THANKS = "Thanks for your feedback!"


def _current_tasks(class_id: int) -> dict[int, dict[str, Any]]:
    """ Each student's current task: the most recently active task, preferring ones in progress. """
    rows = get_db().execute("""
        SELECT p.user_id, p.task_id, p.status, ci.name AS title
        FROM classaid_task_progress p
        LEFT JOIN config_items ci ON ci.id = p.task_id
        WHERE p.class_id = ?
        ORDER BY (p.status = 'in_progress') ASC, p.updated_at ASC
    """, [class_id]).fetchall()
    # later rows win: in-progress tasks, most recently updated
    return {row['user_id']: {'id': row['task_id'], 'title': row['title'], 'status': row['status']} for row in rows}


@bp.route('/api/modes')
@api_route(instructor=True)
def modes_list(ctx: ClassContext) -> Response:
    """ Every student in the class with their effective mode, its source, and current task. """
    db = get_db()
    names = {
        row['id']: row['display_name']
        for row in db.execute("SELECT id, display_name FROM users WHERE id IN (SELECT user_id FROM roles WHERE class_id=?)", [ctx.class_id])
    }
    tasks = _current_tasks(ctx.class_id)
    students = []
    for sid in class_student_ids(ctx.class_id):
        eff = get_effective_mode(ctx.class_id, sid)
        students.append({
            'user_id': sid,
            'name': names.get(sid),
            'mode': eff.mode,
            'source': eff.source,
            'current_task': tasks.get(sid),
        })
    return jsonify(class_mode=get_class_mode(ctx.class_id), students=students)


@bp.route('/api/modes/class', methods=['PUT'])
@api_route(instructor=True)
def modes_set_class(ctx: ClassContext) -> Response:
    """ Set all: apply a mode to the whole class (clears individual modes). """
    mode = parse_mode(json_body().get('mode'))
    set_class_mode(ctx, mode)
    return jsonify(class_mode=mode)


@bp.route('/api/modes/students/<int:student_id>', methods=['PUT', 'DELETE'])
@api_route(instructor=True)
def modes_set_student(ctx: ClassContext, student_id: int) -> Response:
    """ PUT {"mode": ...}: set a student's individual mode.  DELETE: clear it (back to the class mode). """
    mode = parse_mode(json_body().get('mode')) if request.method == 'PUT' else None
    effective = set_student_mode(ctx, student_id, mode)
    return jsonify(user_id=student_id, **msgspec.to_builtins(effective))


@bp.route('/api/tasks/<int:task_id>/ask', methods=['POST'])
@api_route(enabled_class=True)
def task_ask(ctx: ClassContext, task_id: int) -> Response:
    """ Ask the TA Agent a question about the task.  The question is saved immediately; the
    reply (AI feedback, or a notice in Silent mode / on errors) is generated by a job.
    """
    task = task_or_404(ctx, task_id)
    body = json_body()
    question = body.get('question')
    if not isinstance(question, str) or not question.strip():
        raise ApiError(400, "A question is required.")
    if len(question) > MAX_QUESTION_CHARS:
        raise ApiError(400, f"Your question is too long (max {MAX_QUESTION_CHARS:,} characters).")
    files = validate_files(task, body.get('files'))
    progress = require_in_progress(ctx, task)   # completed tasks are read-only, chat included
    save_files(ctx, task, files, reason='question')
    question_id, job_id = submit_question(ctx, task, progress.id, files, question.strip())
    return make_response(jsonify(message_id=question_id, job_id=job_id), 202)


@bp.route('/api/tasks/<int:task_id>/messages')
@api_route()
def task_messages(ctx: ClassContext, task_id: int) -> Response:
    """ The caller's chat messages for the task (optionally only those after ?after=<id>). """
    task = task_or_404(ctx, task_id)
    assert task.row_id is not None
    progress = get_progress(ctx.user_id, task.row_id)
    after = request.args.get('after', default=0, type=int)
    return jsonify(messages=list_messages(progress.id, after_id=after) if progress else [])


@bp.route('/api/messages/<int:message_id>/rating', methods=['PUT'])
@api_route()
def message_rating(ctx: ClassContext, message_id: int) -> Response:
    """ Rate one of the caller's AI messages: {"value": 1 (helpful), -1 (not helpful), or null (withdraw)}. """
    value = json_body().get('value', 'missing')
    if value not in (1, -1, None):
        raise ApiError(400, "Rating must be 1, -1, or null.")
    db = get_db()
    row = db.execute(
        "SELECT task_id, current_rating FROM classaid_messages WHERE id=? AND user_id=? AND class_id=? AND role='assistant'",
        [message_id, ctx.user_id, ctx.class_id],
    ).fetchone()
    if row is None:
        raise ApiError(404, "Message not found.")
    db.execute("UPDATE classaid_messages SET current_rating=? WHERE id=?", [value, message_id])
    log_event(ctx, 'rating', task_id=row['task_id'], payload={'message_id': message_id, 'value': value, 'previous': row['current_rating']})
    db.commit()
    return jsonify(message_id=message_id, rating=value, message=RATING_THANKS)


@bp.route('/api/export/events.jsonl')
@api_route(instructor=True)
def export_events(ctx: ClassContext) -> Response:
    """ The class's complete activity log as JSON Lines (one event per line, in order). """
    lines = list(export_class_events(ctx.class_id))   # materialize inside the app context
    return Response(lines, mimetype='application/x-ndjson', headers={
        'Content-Disposition': f'attachment; filename="classaid_class{ctx.class_id}_events.jsonl"',
    })


MAX_POLLED_JOBS = 20


@bp.route('/api/state')
@api_route()
def state(ctx: ClassContext) -> Response:
    """ Polled by the student workspace every few seconds.  Query parameters:
      task=<id>      include the caller's new chat messages for this task ...
      after=<id>     ... with ids greater than this cursor (default 0: all)
      jobs=<id,...>  include the status (and results) of these jobs of the caller's
    Always includes the caller's current effective feedback mode.
    """
    effective = get_effective_mode(ctx.class_id, ctx.user_id)
    data: dict[str, Any] = {'mode': msgspec.to_builtins(effective)}

    if (task_id := request.args.get('task', type=int)) is not None:
        task = task_or_404(ctx, task_id)
        assert task.row_id is not None
        progress = get_progress(ctx.user_id, task.row_id)
        after = request.args.get('after', default=0, type=int)
        data['messages'] = list_messages(progress.id, after_id=after) if progress else []
        data['task_status'] = progress.status if progress else None

    job_ids = [int(j) for j in request.args.get('jobs', '').split(',') if j.strip().isdigit()][:MAX_POLLED_JOBS]
    jobs = []
    for job_id in job_ids:
        try:
            jobs.append(job_view(ctx, job_id))
        except ApiError:
            continue   # not the caller's job (or gone): omit
    data['jobs'] = jobs
    return jsonify(data)
